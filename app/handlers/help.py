from aiogram import Router, F
from aiogram.types import Message
from aiogram.filters import StateFilter


router = Router()


@router.message(
    StateFilter(None),
    F.text == "Помощь"
)
async def help_handler(message: Message):
    await message.answer(
        "🛠 Помощь — Service Desk\n\n"
        "Service Desk — бот для создания и отслеживания "
        "заявок на техническую поддержку.\n\n"

        "📋 Создать заявку\n"
        "1. Введите название проблемы.\n"
        "2. Выберите категорию.\n"
        "3. Опишите проблему подробнее.\n"
        "4. Проверьте данные и подтвердите отправку.\n\n"
        "После создания заявке присваивается номер.\n\n"

        "📂 Мои заявки\n"
        "Здесь отображаются ваши активные заявки:\n"
        "🆕 Новая — ожидает рассмотрения.\n"
        "🔄 В работе — обрабатывается специалистом.\n\n"
        "Закрытые заявки не отображаются в списке.\n\n"

        "🔔 Уведомления\n"
        "Бот сообщит, когда ваша заявка будет взята "
        "в работу или закрыта.\n\n"
        
        "Если проблема не решена после закрытия заявки, "
        "создайте новое обращение."
    )